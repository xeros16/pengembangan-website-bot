import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
test('shared index setup creates notification outbox index without dropping existing indexes', () => {
  const source = fs.readFileSync(path.join(root, 'scripts/ensure-directory-indexes.js'), 'utf8');
  assert.match(source, /designerId: 1/);
  assert.match(source, /ownerJid: 1/);
  assert.match(source, /itemId: 1, moderationStatus: 1/);
  assert.match(source, /itemId_1_moderationStatus_1/);
  assert.match(source, /notificationId: 1/);
  assert.match(source, /designerId: 1, readAt: 1, createdAt: -1/);
  assert.match(source, /whatsappDeliveryStatus: 1, whatsappNextAttemptAt: 1, createdAt: 1/);
  assert.match(source, /createIndex/);
  assert.match(source, /designbriefsessions/);
  assert.match(source, /chatJid: 1, userJid: 1/);
  assert.match(source, /expireAfterSeconds: 0/);
  assert.match(source, /designbattles/);
  assert.match(source, /designseasons/);
  assert.match(source, /designseasonsubmissions/);
  assert.match(source, /creativeassets/);
  assert.match(source, /groupJid_1_active_unique/);
  assert.match(source, /groupJid_1_seasonCode_1_roundCode_1_userJid_1/);
  assert.match(source, /groupJid_1_visibility_1_status_1_category_1_updatedAt_-1/);
  assert.match(source, /groupJid: 1, status: 1, endsAt: 1/);
  assert.match(source, /groupJid_1_open_unique/);
  assert.match(source, /learningcohorts/);
  assert.match(source, /groupJid_1_status_1_createdAt_-1/);
  assert.match(source, /learningcohortcheckins/);
  assert.match(source, /groupJid_1_cohortCode_1_milestoneCode_1_userJid_1/);
  assert.match(source, /code: 1/);
  assert.doesNotMatch(source, /dropIndex|dropIndexes/);
});
